// Turn a word set in Excalifont into glyph outlines so the hero can "write"
// it stroke by stroke (CSS draws the outline, then fills it).
//   node tools/name.mjs [word]      -> _includes/name-paths.html
// Not part of `npm run build`; the include is committed.
import { readFileSync, writeFileSync } from "node:fs";
import subsetFont from "subset-font";
import opentype from "opentype.js";

const word = process.argv[2] || "rahul";
const woff2 = readFileSync("assets/fonts/excalifont.woff2");
// opentype.js wants a plain TrueType buffer; subset-font converts woff2 -> sfnt.
const ttf = await subsetFont(woff2, word, { targetFormat: "sfnt" });
const font = opentype.parse(ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength));

const size = font.unitsPerEm;
const ascender = font.ascender;
const height = font.ascender - font.descender;
const advance = font.getAdvanceWidth(word, size);
const paths = font.getPaths(word, 0, ascender, size).map((p) => p.toPathData(1)).filter(Boolean);

const svg =
  `<svg class="name" viewBox="0 0 ${Math.round(advance)} ${height}" aria-hidden="true" focusable="false">` +
  paths.map((d) => `<path class="name__glyph" pathLength="1" d="${d}"/>`).join("") +
  "</svg>";
writeFileSync("_includes/name-paths.html", `{% comment %}Generated by tools/name.mjs ("${word}") - do not edit by hand.{% endcomment %}\n${svg}\n`);
console.log(`name-paths.html: "${word}" as ${paths.length} glyph paths, viewBox 0 0 ${Math.round(advance)} ${height}`);
